/* These functions run inside the IIFE — patched in as standalone module
   after DOMContentLoaded because the IIFE already sealed. */

(function () {
  'use strict';

  /* ─── STORAGE HELPERS (mirrors IIFE internals) ─────────────────── */
  const CQ_KEY  = 'jc_beta_carried_question_v1';
  const CQR_KEY = 'jc_beta_carried_records_v1';   // array of record ids visited while carrying
  const CQS_KEY = 'jc_beta_cq_status_v1';         // 'open' | 'received'

  function sq(k, v)    { try { localStorage.setItem(k, JSON.stringify(v)); } catch(_){} }
  function gq(k, fb)   { try { const r = localStorage.getItem(k); return r !== null ? JSON.parse(r) : fb; } catch(_) { return fb; } }
  function esc(s)      { return String(s).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c])); }

  /* ─── CARRY A QUESTION (§10) ───────────────────────────────────── */

  function initCarryQuestion() {
    const section = document.querySelector('.carry-question-section');
    if (!section) return;

    const currentQuestion = gq(CQ_KEY, null);
    const activeEl   = section.querySelector('.carry-question__active');
    const statusEl   = section.querySelector('.carry-question__status');
    const fieldEl    = section.querySelector('.carry-question__field');
    const btnCarry   = section.querySelector('[data-cq-action="carry"]');
    const btnCustom  = section.querySelector('[data-cq-action="write"]');
    const btnClear   = section.querySelector('[data-cq-action="clear"]');
    const btnSave    = section.querySelector('[data-cq-action="save"]');

    // Track this record visit if carrying a question
    const bodyRecordId = document.body.dataset && document.body.dataset.recordId;
    if (currentQuestion && bodyRecordId && bodyRecordId !== 'thread-constellation-beta') {
      let visited = gq(CQR_KEY, []);
      if (!visited.includes(bodyRecordId)) {
        visited.push(bodyRecordId);
        sq(CQR_KEY, visited);
      }
    }

    function render() {
      const q      = gq(CQ_KEY, null);
      const status = gq(CQS_KEY, 'open');
      const visited = gq(CQR_KEY, []);

      if (activeEl) {
        if (q) {
          activeEl.classList.add('is-shown');
          activeEl.textContent = '"' + q + '"';
        } else {
          activeEl.classList.remove('is-shown');
        }
      }
      if (statusEl) {
        if (q) {
          const vCount = visited.length;
          statusEl.classList.add('is-shown');
          statusEl.textContent = 'Status: ' + status
            + (vCount > 0 ? ' · Records encountered: ' + vCount : '')
            + ' · Stored locally on this device only.';
        } else {
          statusEl.classList.remove('is-shown');
        }
      }
      // Show/hide clear and carry buttons
      if (btnClear) btnClear.style.display = q ? 'inline-flex' : 'none';
      if (btnCarry) btnCarry.textContent = q ? 'Keep carrying this question' : 'Carry this question forward';
    }

    // "Carry this question" — uses the record's own title-question (data attr) or a default
    if (btnCarry) {
      const defaultQuestion = section.dataset.defaultQuestion || 'What did I actually encounter here?';
      btnCarry.addEventListener('click', () => {
        sq(CQ_KEY, defaultQuestion);
        sq(CQS_KEY, 'open');
        if (fieldEl) fieldEl.classList.remove('is-shown');
        render();
      });
    }

    // "Write my own question" — reveal textarea
    if (btnCustom) {
      btnCustom.addEventListener('click', () => {
        if (fieldEl) {
          fieldEl.classList.toggle('is-shown');
          if (fieldEl.classList.contains('is-shown')) {
            fieldEl.focus();
            if (btnSave) btnSave.style.display = 'inline-flex';
          } else {
            if (btnSave) btnSave.style.display = 'none';
          }
        }
      });
    }

    // Save custom question
    if (btnSave && fieldEl) {
      btnSave.addEventListener('click', () => {
        const val = fieldEl.value.trim();
        if (val) {
          sq(CQ_KEY, val);
          sq(CQS_KEY, 'open');
          sq(CQR_KEY, []);
          fieldEl.classList.remove('is-shown');
          btnSave.style.display = 'none';
          render();
        }
      });
    }

    // Clear
    if (btnClear) {
      btnClear.addEventListener('click', () => {
        sq(CQ_KEY, null);
        sq(CQS_KEY, null);
        sq(CQR_KEY, []);
        if (fieldEl) fieldEl.classList.remove('is-shown');
        render();
      });
    }

    render();
  }

  /* ─── DISCERN STEP (§5.2 — four movements: Name / Receive / Discern / Return) ─ */

  function initDiscernStep() {
    const section = document.querySelector('.discern-section');
    if (!section) return;

    const choices = section.querySelectorAll('.discern-choice[data-reveals]');
    choices.forEach(btn => {
      btn.addEventListener('click', () => {
        // Deactivate siblings
        choices.forEach(b => {
          b.setAttribute('aria-pressed', 'false');
          const rid = b.dataset.reveals;
          if (rid) {
            const resp = document.getElementById(rid);
            if (resp) resp.hidden = true;
          }
        });

        btn.setAttribute('aria-pressed', 'true');

        // Show this response
        const targetId = btn.dataset.reveals;
        const target = targetId ? document.getElementById(targetId) : null;
        if (target) {
          target.hidden = false;
          // Smooth scroll to response, giving a moment for layout
          requestAnimationFrame(() => {
            target.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
          });
        }

        // Show the return panel if it exists
        const returnPanel = document.getElementById('return-panel');
        if (returnPanel) returnPanel.hidden = false;
      });
    });
  }

  /* ─── RELEASE / RETURN CHOICES ─────────────────────────────────── */

  function initReleaseChoices() {
    document.querySelectorAll('[data-release-action]').forEach(el => {
      el.addEventListener('click', (e) => {
        const action = el.dataset.releaseAction;
        switch (action) {
          case 'remain':
            e.preventDefault();
            window.scrollTo({ top: 0, behavior: 'smooth' });
            break;
          case 'thread':
            window.location.href = el.dataset.href || '../threads.html';
            break;
          case 'paths':
            window.location.href = el.dataset.href || '../paths.html';
            break;
          case 'scripture':
            e.preventDefault();
            const scrEl = document.getElementById('scripture-section');
            if (scrEl) scrEl.scrollIntoView({ behavior: 'smooth' });
            break;
          case 'mystery':
            window.location.href = el.dataset.href || '../mystery.html';
            break;
          case 'leave':
            e.preventDefault();
            el.textContent = 'You may return when ready.';
            el.disabled = true;
            el.style.opacity = '0.5';
            break;
        }
      });
    });
  }

  /* ─── INIT ─────────────────────────────────────────────────────── */

  document.addEventListener('DOMContentLoaded', function () {
    initCarryQuestion();
    initDiscernStep();
    initReleaseChoices();
  });

})();
