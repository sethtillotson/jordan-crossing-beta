/**
 * Jordan Crossing Beta — Shared Logic
 * Local-only bookmarks, carried-question state, no-interpretation toggle
 * No external dependencies. No server calls. No account required.
 * All state is localStorage only and never transmitted.
 */

'use strict';

/* ─── NAMESPACE ─────────────────────────────────────────────────────── */

const JC = (function () {

  /* ─── STORAGE KEYS ─────────────────────────────────────────────── */
  const KEYS = {
    bookmarks:       'jc_beta_bookmarks_v1',
    carriedQuestion: 'jc_beta_carried_question_v1',
    noInterp:        'jc_beta_no_interp_v1',
    lastRecord:      'jc_beta_last_record_v1',
  };

  /* ─── SAFE localStorage ─────────────────────────────────────────── */
  function storageGet(key, fallback) {
    try {
      const raw = localStorage.getItem(key);
      return raw !== null ? JSON.parse(raw) : fallback;
    } catch { return fallback; }
  }

  function storageSet(key, value) {
    try { localStorage.setItem(key, JSON.stringify(value)); } catch { /* quota exceeded — silent */ }
  }

  /* ─── BOOKMARKS ─────────────────────────────────────────────────── */

  function getBookmarks() {
    return storageGet(KEYS.bookmarks, []);
  }

  function isBookmarked(recordId) {
    return getBookmarks().includes(recordId);
  }

  function toggleBookmark(recordId) {
    let bm = getBookmarks();
    if (bm.includes(recordId)) {
      bm = bm.filter(id => id !== recordId);
    } else {
      bm.push(recordId);
    }
    storageSet(KEYS.bookmarks, bm);
    return bm.includes(recordId);
  }

  function renderBookmarkBtn(btn, recordId) {
    if (!btn) return;
    const marked = isBookmarked(recordId);
    btn.classList.toggle('is-bookmarked', marked);
    btn.setAttribute('aria-pressed', String(marked));
    btn.title = marked ? 'Remove bookmark' : 'Bookmark this record';
  }

  function initBookmarkButtons() {
    document.querySelectorAll('[data-bookmark-id]').forEach(btn => {
      const id = btn.dataset.bookmarkId;
      renderBookmarkBtn(btn, id);
      btn.addEventListener('click', () => {
        toggleBookmark(id);
        renderBookmarkBtn(btn, id);
      });
    });
  }

  /* ─── CARRIED QUESTION ──────────────────────────────────────────── */

  function getCarriedQuestion() {
    return storageGet(KEYS.carriedQuestion, null);
  }

  function setCarriedQuestion(text) {
    storageSet(KEYS.carriedQuestion, text || null);
  }

  function clearCarriedQuestion() {
    storageSet(KEYS.carriedQuestion, null);
  }

  function renderCarriedQuestionBar() {
    const bar = document.getElementById('carried-question-bar');
    if (!bar) return;
    const q = getCarriedQuestion();
    const textEl = bar.querySelector('.carried-question__text');
    if (q) {
      bar.classList.remove('is-hidden');
      if (textEl) textEl.textContent = q;
    } else {
      bar.classList.add('is-hidden');
    }
  }

  function initCarriedQuestion() {
    renderCarriedQuestionBar();

    // Clear button
    const clearBtn = document.querySelector('.carried-question__clear');
    if (clearBtn) {
      clearBtn.addEventListener('click', () => {
        clearCarriedQuestion();
        renderCarriedQuestionBar();
      });
    }
  }

  /* ─── NO-INTERPRETATION TOGGLE ──────────────────────────────────── */

  function getNoInterp() {
    return storageGet(KEYS.noInterp, false);
  }

  function setNoInterp(val) {
    storageSet(KEYS.noInterp, !!val);
  }

  function applyNoInterp(state) {
    document.body.classList.toggle('no-interp', state);
    const toggle = document.getElementById('no-interp-toggle');
    if (toggle) {
      toggle.checked = state;
      toggle.setAttribute('aria-checked', String(state));
    }
    const label = document.getElementById('no-interp-label');
    if (label) {
      label.textContent = state
        ? 'Original record only — editorial layers hidden'
        : 'Show all layers including editorial orientation';
    }
  }

  function initNoInterpToggle() {
    const toggle = document.getElementById('no-interp-toggle');
    if (!toggle) return;

    // Restore saved state
    applyNoInterp(getNoInterp());

    toggle.addEventListener('change', () => {
      const next = toggle.checked;
      setNoInterp(next);
      applyNoInterp(next);
    });
  }

  /* ─── SOURCE BADGE TOOLTIPS ─────────────────────────────────────── */

  const SOURCE_DESCRIPTIONS = {
    'original':   'Original record: the author\'s own words, audio, or transcript, as recorded.',
    'reviewed':   'Human-reviewed orientation: written or approved by a human editor to help readers enter the record. Not the author\'s own meditation text.',
    'editorial':  'Editorial connection: a thematic or chronological link identified by human review. Marked as editorial so you can weigh it.',
    'machine':    'Machine-assisted index: generated by AI for search or categorization purposes. Always verify against the original record. The author\'s words remain primary.',
  };

  function initSourceBadges() {
    document.querySelectorAll('.source-badge[data-source-type]').forEach(badge => {
      const type = badge.dataset.sourceType;
      const desc = SOURCE_DESCRIPTIONS[type] || '';

      // Create or find legend element
      let legend = badge.nextElementSibling;
      if (!legend || !legend.classList.contains('source-legend')) {
        legend = document.createElement('div');
        legend.className = 'source-legend';
        legend.setAttribute('role', 'tooltip');
        legend.setAttribute('aria-live', 'polite');
        badge.insertAdjacentElement('afterend', legend);
      }
      legend.textContent = desc;

      badge.setAttribute('aria-expanded', 'false');
      badge.setAttribute('role', 'button');
      badge.setAttribute('tabindex', '0');

      const toggle = () => {
        const open = legend.classList.toggle('is-open');
        badge.setAttribute('aria-expanded', String(open));
      };

      badge.addEventListener('click', toggle);
      badge.addEventListener('keydown', e => {
        if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); toggle(); }
      });
    });
  }

  /* ─── LAST RECORD TRACKING ──────────────────────────────────────── */

  function setLastRecord(recordId) {
    storageSet(KEYS.lastRecord, recordId || null);
  }

  function getLastRecord() {
    return storageGet(KEYS.lastRecord, null);
  }

  /* ─── MYSTERY MODE DOORWAY SELECTION ────────────────────────────── */

  function initDoorwayButtons() {
    const doorways = document.querySelectorAll('.doorway-btn[data-doorway]');
    const continueBtn = document.getElementById('mystery-continue');
    const promptEl = document.getElementById('selected-doorway-prompt');
    let selected = null;

    doorways.forEach(btn => {
      btn.addEventListener('click', () => {
        doorways.forEach(b => {
          b.classList.remove('is-selected');
          b.setAttribute('aria-pressed', 'false');
        });
        btn.classList.add('is-selected');
        btn.setAttribute('aria-pressed', 'true');
        selected = btn.dataset.doorway;

        // Save as carried question
        const questionText = btn.dataset.questionText || btn.textContent.trim();
        setCarriedQuestion(questionText);

        if (continueBtn) {
          continueBtn.disabled = false;
          continueBtn.removeAttribute('disabled');
        }

        if (promptEl) {
          promptEl.textContent = btn.dataset.guidance || '';
          promptEl.hidden = false;
        }
      });
    });

    if (continueBtn) {
      continueBtn.addEventListener('click', () => {
        if (!selected) return;
        // Doorway → record-id map. Keys MUST match data-doorway values in mystery.html exactly;
        // a prior mismatch (full-chronology/quiet-beginning/unknown vs. the real
        // signpost/jordan-crossing/compass ids) silently misrouted three doorways.
        // See living-topology/JORDAN_CROSSING_MYSTERY_MODE_AND_PUBLIC_WITNESS_DESIGN.md §5.5:
        // 'every edge must resolve to the correct source record.'
        const doorwayToRecordId = {
          'beginning-again':   'signpost',
          'trapped-identity':  'man-of-flesh',
          'waiting':           'wisdom',
          'cannot-see':        'compass',
          'cost-of-obedience': 'filthy-garments',
          'surrender':         'man-of-flesh',
          'searching-jesus':   'jordan-crossing',
          'examine-carefully': 'jordan-crossing',
          'signpost':          'signpost',
          'jordan-crossing':   'jordan-crossing',
          'compass':           'compass',
        };
        const recordId = doorwayToRecordId[selected] || 'compass';
        window.location.href = (typeof jcHrefFor === 'function') ? jcHrefFor(recordId) : 'records/08-30-compass.html';
      });
    }
  }

  /* ─── TABLET STATUS CHIPS ───────────────────────────────────────── */
  // Static — no dynamic behavior needed; rendered in HTML

  /* ─── NAV PLACEHOLDER LABELS ────────────────────────────────────── */
  // Placeholders are static HTML with class .nav-placeholder

  /* ─── RETURN PASSAGE CHOICES (record.html) ──────────────────────── */

  function initReturnChoices() {
    const choices = document.querySelectorAll('.return-choice[data-action]');
    choices.forEach(btn => {
      btn.addEventListener('click', () => {
        const action = btn.dataset.action;
        switch (action) {
          case 'remain':
            window.scrollTo({ top: 0, behavior: 'smooth' });
            break;
          case 'follow':
            window.location.href = 'threads.html';
            break;
          case 'scripture':
            // Scripture is inline — scroll to scripture section
            const scr = document.getElementById('scripture-section');
            if (scr) scr.scrollIntoView({ behavior: 'smooth' });
            break;
          case 'leave':
            // Simply acknowledge — the reader can close or navigate away
            btn.textContent = 'Return when ready.';
            btn.disabled = true;
            break;
        }
      });
    });
  }

  /* ─── DISCERN CHOICES (record.html) ─────────────────────────────── */

  function initDiscernChoices() {
    const choices = document.querySelectorAll('.discern-choice[data-reveals]');
    choices.forEach(btn => {
      btn.addEventListener('click', () => {
        const targetId = btn.dataset.reveals;
        const target = document.getElementById(targetId);
        if (target) {
          target.hidden = false;
          target.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
        }
        choices.forEach(b => b.setAttribute('aria-pressed', 'false'));
        btn.setAttribute('aria-pressed', 'true');
      });
    });
  }

  /* ─── GRAPH NAV (prev/next chronology + reviewed edges) ─────────── */

  function escapeHtml(s) {
    return String(s).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  }

  function initGraphNav() {
    const mount = document.getElementById('graph-nav-mount');
    if (!mount) return;
    if (typeof JC_RECORDS === 'undefined') return;
    const recordId = mount.dataset.recordId;
    if (!recordId) return;

    const isInterior = recordId === 'jordan-crossing';
    const { prev, next } = isInterior ? { prev: null, next: null } : jcGetPrevNext(recordId);
    const { outgoing, incoming } = jcGetEdgesFor(recordId);
    // This mount is reused on two different path depths: individual pages under
    // records/*.html (need '../' + bare filename) and root-level pages like
    // record.html (need 'records/' + filename). Pick the right href builder
    // by checking where this script is actually running.
    const insideRecordsDir = /\/records\//.test(location.pathname);
    const hrefFor = insideRecordsDir ? jcHrefFromRecord : jcHrefFor;

    const posLabel = (() => {
      if (recordId === 'jordan-crossing') return 'The preserved interior record · outside the seven-seed constellation below';
      const rec = jcGetRecord(recordId);
      return rec ? `Seed ${rec.seed} of the Tablet VIII register · chronological order ${rec.order} of ${JC_RECORDS.length}` : '';
    })();

    const prevHtml = prev
      ? `<a class="graph-nav-prev" href="${hrefFor(prev.id)}">&larr; ${escapeHtml(prev.title)}</a>`
      : `<span class="graph-nav-prev" style="color:var(--stone);">&larr; Beginning of this constellation</span>`;
    const nextHtml = next
      ? `<a class="graph-nav-next" href="${hrefFor(next.id)}">${escapeHtml(next.title)} &rarr;</a>`
      : `<span class="graph-nav-next" style="color:var(--stone);">End of this constellation &rarr;</span>`;
    const chronoRowHtml = isInterior ? '' : `
      <div class="graph-nav-chrono">
        ${prevHtml}
        <span class="graph-nav-position">${escapeHtml(posLabel)}</span>
        ${nextHtml}
      </div>`;

    function edgeRow(e, direction) {
      const otherId = direction === 'out' ? e.to : e.from;
      const label = direction === 'out' ? (EDGE_LABELS[e.type] || e.type) : `is ${EDGE_LABELS[e.type] || e.type} by`;
      const href = hrefFor(otherId);
      const title = jcTitleFor(otherId);
      return `<li class="edge-item"><div class="edge-head"><span class="edge-type">${escapeHtml(label)}</span><a class="edge-target" href="${href}">${escapeHtml(title)}</a><span class="thread-status thread-status--${e.status === 'author-confirmed' ? 'confirmed' : e.status === 'editorial' ? 'editorial' : 'open'}">${escapeHtml(STATUS_LABELS[e.status] || e.status)}</span></div><p class="edge-note">${escapeHtml(e.note)}</p><p class="edge-source">Source: ${escapeHtml(e.source)}</p></li>`;
    }

    const edgeItems = [...outgoing.map(e => edgeRow(e, 'out')), ...incoming.map(e => edgeRow(e, 'in'))];
    const edgesHtml = edgeItems.length
      ? `<ul class="edge-list">${edgeItems.join('')}</ul>`
      : `<p class="edge-empty">No reviewed bridge is recorded from this page yet. That absence is reported, not filled.</p>`;

    mount.innerHTML = `
      ${chronoRowHtml}
      <div class="graph-nav-edges">
        <h3>Reviewed thread connections</h3>
        ${isInterior ? `<p class="caption" style="margin-bottom:var(--space-3);">${escapeHtml(posLabel)}</p>` : ''}
        ${edgesHtml}
      </div>
    `;
  }

  /* ─── RECORD ROUTING ─────────────────────────────────────────────── */
  // Metadata source of truth lives in assets/records-data.js (JC_RECORDS). This
  // function only reads it — no duplicated title/date/href strings here, so the
  // wrapper and the graph-nav can never drift out of sync again.
  function initRecordRoute() {
    if (!document.body.dataset.recordId || !location.pathname.endsWith('/record.html')) return;
    if (typeof JC_RECORDS === 'undefined') return;
    const key = new URLSearchParams(location.search).get('record') || 'jordan-crossing';
    const isInterior = key === 'jordan-crossing' || !jcGetRecord(key);
    const rec = isInterior ? null : jcGetRecord(key);

    const title = isInterior ? 'The Jordan Crossing' : rec.title;
    const subtitle = isInterior
      ? 'The superseded interior record, now placed inside the larger mystery.'
      : `${rec.dateLabel} · Tablet VIII Seed ${rec.seed}`;
    const href = isInterior ? 'jordan-crossing-interior.html' : rec.href;
    const note = isInterior
      ? 'SOURCE STATUS: original record · Preserved v11 interior HTML.'
      : 'SOURCE STATUS: original record · Imported source meditation.';

    const set = (id, value) => { const el = document.getElementById(id); if (el) el.textContent = value; };
    set('record-title', title); set('record-subtitle', subtitle); set('record-source-note', note);
    const link = document.getElementById('record-source-link');
    if (link) { link.href = href; link.textContent = isInterior ? 'Open the original interior record ↗' : 'Open the source record ↗'; }
    if (!isInterior) set('record-description', 'This beta opens the local source file directly. The page above remains a navigational wrapper; the linked file is the record, not a summary.');

    // Keep the graph-nav mount in sync with whichever record this wrapper is showing.
    const graphMount = document.getElementById('graph-nav-mount');
    if (graphMount) graphMount.dataset.recordId = isInterior ? 'jordan-crossing' : key;
  }

  /* ─── INIT ───────────────────────────────────────────────────────── */

  function init() {
    initBookmarkButtons();
    initCarriedQuestion();
    initNoInterpToggle();
    initSourceBadges();
    initDoorwayButtons();
    initReturnChoices();
    initDiscernChoices();
    initRecordRoute();
    initGraphNav();

    // Record tracking: if there's a data-record-id on body, log it
    const recordId = document.body.dataset.recordId;
    if (recordId) setLastRecord(recordId);
  }

  document.addEventListener('DOMContentLoaded', init);

  /* ─── PUBLIC API ─────────────────────────────────────────────────── */
  return {
    getBookmarks,
    isBookmarked,
    toggleBookmark,
    getCarriedQuestion,
    setCarriedQuestion,
    clearCarriedQuestion,
    getLastRecord,
    getNoInterp,
    renderCarriedQuestion,
  };

})();

